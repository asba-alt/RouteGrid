from fastapi import APIRouter, Depends
from sqlalchemy.ext.asyncio import AsyncSession

from app.core.auth import CurrentUser, get_current_user
from app.db.session import get_db
from app.schemas.simulation import AdvanceRequest, AdvanceResponse, VehiclePositionRead
from app.services import simulation_service

router = APIRouter(prefix="/api/v1/simulation", tags=["simulation"])


@router.get("/positions", response_model=list[VehiclePositionRead])
async def current_positions(
    db: AsyncSession = Depends(get_db),
    user: CurrentUser = Depends(get_current_user),
) -> list[VehiclePositionRead]:
    """Current simulated position of every active vehicle.

    Populated from the Redis cache when available, otherwise derived from the
    route's last completed stop. Used by the live tracking map.
    """
    return await simulation_service.current_positions(db)


@router.post("/advance", response_model=AdvanceResponse)
async def advance_simulation(
    payload: AdvanceRequest,
    db: AsyncSession = Depends(get_db),
    user: CurrentUser = Depends(get_current_user),
) -> AdvanceResponse:
    """Advance simulated vehicle movement along assigned routes.

    Positions are generated by an in-process simulator in compressed time; they
    are not measurements from real GPS hardware.
    """
    return await simulation_service.advance(
        db, payload.elapsed_seconds, route_id=payload.route_id
    )
